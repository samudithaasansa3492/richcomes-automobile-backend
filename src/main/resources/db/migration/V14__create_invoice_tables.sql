CREATE TABLE garage.sales_invoices (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       service_job_id INTEGER NOT NULL REFERENCES garage.service_jobs(id),
                                       customer_id BIGINT NOT NULL REFERENCES garage.customers(id),
                                       vehicle_id BIGINT REFERENCES garage.vehicles(id),
                                       invoice_no VARCHAR(50) UNIQUE,
                                       invoice_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                       status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                                       subtotal NUMERIC NOT NULL CHECK (subtotal >= 0),
                                       discount_amount NUMERIC NOT NULL DEFAULT 0,
                                       total_amount NUMERIC NOT NULL CHECK (total_amount >= 0),
                                       CONSTRAINT chk_sales_invoice_status
                                           CHECK (status IN ('DRAFT', 'ISSUED', 'PAID', 'CANCELLED')),
                                       CONSTRAINT chk_sales_invoice_discount
                                           CHECK (discount_amount >= 0 AND discount_amount <= subtotal)
);

CREATE INDEX idx_sales_invoices_job
    ON garage.sales_invoices(service_job_id);

CREATE TABLE garage.sales_invoice_items (
                                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            invoice_id BIGINT NOT NULL REFERENCES garage.sales_invoices(id),
                                            item_type VARCHAR(20) NOT NULL
                                                CHECK (item_type IN ('LABOUR', 'PART', 'OTHER')),
                                            item_reference_id BIGINT CHECK (item_reference_id > 0),
                                            description VARCHAR(255) NOT NULL,
                                            quantity NUMERIC NOT NULL CHECK (quantity > 0),
                                            unit_price NUMERIC(19, 2) NOT NULL CHECK (unit_price >= 0),
                                            total_amount NUMERIC NOT NULL CHECK (total_amount >= 0)
);

CREATE INDEX idx_sales_invoice_items_invoice
    ON garage.sales_invoice_items(invoice_id);