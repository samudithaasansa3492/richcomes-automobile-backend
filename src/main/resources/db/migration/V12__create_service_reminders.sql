CREATE TABLE garage.service_reminders (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    vehicle_id BIGINT NOT NULL,
    customer_id BIGINT NOT NULL,

    service_history_id BIGINT,

    next_service_date DATE NOT NULL,
    reminder_date DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    message TEXT NOT NULL,

    notification_id BIGINT,

    ai_suggested_date DATE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Validate reminder status
    CONSTRAINT chk_service_reminders_status
        CHECK (
            status IN ('PENDING', 'SENT', 'CANCELLED')
        ),

    -- Reminder must be on or before next service date
    CONSTRAINT chk_service_reminders_dates
        CHECK (
            reminder_date <= next_service_date
        ),

    -- Link reminder to service history
    CONSTRAINT fk_service_reminders_history
        FOREIGN KEY (service_history_id)
        REFERENCES garage.service_history(id),

    -- Link reminder to vehicle
    CONSTRAINT fk_service_reminders_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES garage.vehicles(id),

    -- Link reminder to customer
    CONSTRAINT fk_service_reminders_customer
        FOREIGN KEY (customer_id)
        REFERENCES garage.customers(id),

    -- Link reminder to queued notification
    CONSTRAINT fk_service_reminders_notification
        FOREIGN KEY (notification_id)
        REFERENCES garage.notifications(id)
);

-- 2. PREVENT DUPLICATE REMINDERS
-- One reminder per service history record.

CREATE UNIQUE INDEX ux_service_reminders_history
ON garage.service_reminders (service_history_id)
WHERE service_history_id IS NOT NULL;

-- 3. IMPROVE SCHEDULER PERFORMANCE
-- Find reminders that have not yet queued a notification.

CREATE INDEX idx_service_reminders_due_unqueued
ON garage.service_reminders (reminder_date)
WHERE notification_id IS NULL;

-- 4. IMPROVE CUSTOMER SEARCHES

CREATE INDEX idx_service_reminders_customer
ON garage.service_reminders (customer_id);

-- 5. IMPROVE VEHICLE SEARCHES

CREATE INDEX idx_service_reminders_vehicle
ON garage.service_reminders (vehicle_id);

-- 6. IMPROVE REMINDER STATUS SEARCHES

CREATE INDEX idx_service_reminders_status
ON garage.service_reminders (status);

