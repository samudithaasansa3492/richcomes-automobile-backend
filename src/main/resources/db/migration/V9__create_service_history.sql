DROP TABLE IF EXISTS garage.service_history;
CREATE TABLE garage.service_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    vehicle_id BIGINT NOT NULL,
    job_id BIGINT NOT NULL UNIQUE,

    service_date DATE NOT NULL,
    odometer INTEGER NOT NULL,
    summary TEXT NOT NULL,

    technician_id BIGINT NOT NULL,
    invoice_id BIGINT,

    total_cost NUMERIC(12, 2) NOT NULL,
    next_service_date DATE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_service_history_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES garage.vehicles(id),

    CONSTRAINT chk_service_history_odometer
        CHECK (odometer >= 0),

    CONSTRAINT chk_service_history_cost
        CHECK (total_cost >= 0)
);

CREATE INDEX idx_service_history_vehicle
    ON garage.service_history(vehicle_id);

CREATE INDEX idx_service_history_job
    ON garage.service_history(job_id);

CREATE INDEX idx_service_history_date
    ON garage.service_history(service_date);
