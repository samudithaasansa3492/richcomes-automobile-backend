CREATE TABLE garage.service_job_items (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          service_job_id INTEGER NOT NULL
                                              REFERENCES garage.service_jobs(id),
                                          service_item_id INTEGER NOT NULL
                                              REFERENCES garage.service_items(id),
                                          labour_hours DOUBLE PRECISION,
                                          labour_rate NUMERIC(19, 2),
                                          total_amount NUMERIC(19, 2)
);

CREATE INDEX idx_service_job_items_job
    ON garage.service_job_items(service_job_id);

CREATE TABLE garage.service_job_parts (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          service_job_id INTEGER NOT NULL
                                              REFERENCES garage.service_jobs(id),
                                          part_id BIGINT NOT NULL,
                                          quantity DOUBLE PRECISION,
                                          unit_price NUMERIC(19, 2),
                                          total_amount NUMERIC(19, 2)
);

CREATE INDEX idx_service_job_parts_job
    ON garage.service_job_parts(service_job_id);