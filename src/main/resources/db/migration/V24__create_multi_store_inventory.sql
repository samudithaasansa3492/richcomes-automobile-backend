
-- Multi-store inventory support


-- 1. Store locations

CREATE TABLE garage.store_locations (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        store_code VARCHAR(30) NOT NULL,
                                        store_name VARCHAR(150) NOT NULL,
                                        address VARCHAR(255),
                                        active BOOLEAN NOT NULL DEFAULT TRUE,

                                        CONSTRAINT uk_store_locations_code
                                            UNIQUE (store_code)
);

-- 2. Product quantities per store

CREATE TABLE garage.store_stock_balances (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             store_location_id BIGINT NOT NULL,
                                             stock_item_id BIGINT NOT NULL,
                                             quantity NUMERIC(14,3) NOT NULL DEFAULT 0,

                                             CONSTRAINT fk_store_balance_location
                                                 FOREIGN KEY (store_location_id)
                                                     REFERENCES garage.store_locations(id),

                                             CONSTRAINT fk_store_balance_item
                                                 FOREIGN KEY (stock_item_id)
                                                     REFERENCES garage.stock_items(id),

                                             CONSTRAINT uk_store_stock_item
                                                 UNIQUE (store_location_id, stock_item_id),

                                             CONSTRAINT chk_store_balance_quantity
                                                 CHECK (quantity >= 0)
);

CREATE INDEX idx_store_balances_item
    ON garage.store_stock_balances(stock_item_id);

-- 3. GRN item allocations across stores

CREATE TABLE garage.grn_item_allocations (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             grn_item_id BIGINT NOT NULL,
                                             store_location_id BIGINT NOT NULL,
                                             allocated_quantity NUMERIC(14,3) NOT NULL,

                                             CONSTRAINT fk_grn_allocation_item
                                                 FOREIGN KEY (grn_item_id)
                                                     REFERENCES garage.grn_items(id),

                                             CONSTRAINT fk_grn_allocation_store
                                                 FOREIGN KEY (store_location_id)
                                                     REFERENCES garage.store_locations(id),

                                             CONSTRAINT uk_grn_item_store
                                                 UNIQUE (grn_item_id, store_location_id),

                                             CONSTRAINT chk_grn_allocation_quantity
                                                 CHECK (allocated_quantity > 0)
);

CREATE INDEX idx_grn_allocations_store
    ON garage.grn_item_allocations(store_location_id);
