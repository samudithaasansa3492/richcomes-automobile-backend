-- Inventory tables for the garage schema.
-- Apply using Flyway only after confirming the next available version
-- and the project's configured SQL migration filename separator.

CREATE TABLE garage.stock_categories (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         name VARCHAR(100) NOT NULL UNIQUE,
                                         description VARCHAR(500),
                                         active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE garage.suppliers (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  supplier_name VARCHAR(150) NOT NULL,
                                  tin_number VARCHAR(30) UNIQUE,
                                  contact_person VARCHAR(100),
                                  phone VARCHAR(20),
                                  email VARCHAR(150),
                                  address VARCHAR(255),
                                  active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE garage.stock_items (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    item_code VARCHAR(50) NOT NULL UNIQUE,
                                    item_name VARCHAR(150) NOT NULL,
                                    barcode VARCHAR(100) UNIQUE,
                                    description VARCHAR(500),
                                    category_id BIGINT NOT NULL,
                                    image_url VARCHAR(500),
                                    current_quantity INTEGER NOT NULL DEFAULT 0,
                                    reorder_level INTEGER NOT NULL DEFAULT 10,
                                    unit_cost NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
                                    selling_price NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
                                    active BOOLEAN NOT NULL DEFAULT TRUE,
                                    version BIGINT NOT NULL DEFAULT 0,
                                    CONSTRAINT fk_stock_items_category
                                        FOREIGN KEY (category_id) REFERENCES garage.stock_categories(id),
                                    CONSTRAINT chk_stock_items_quantity CHECK (current_quantity >= 0),
                                    CONSTRAINT chk_stock_items_reorder CHECK (reorder_level >= 0),
                                    CONSTRAINT chk_stock_items_cost CHECK (unit_cost >= 0),
                                    CONSTRAINT chk_stock_items_price CHECK (selling_price >= 0)
);

CREATE INDEX idx_stock_items_category_id ON garage.stock_items(category_id);

CREATE TABLE garage.stock_transactions (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           stock_item_id BIGINT NOT NULL,
                                           transaction_type VARCHAR(30) NOT NULL,
                                           quantity INTEGER NOT NULL,
                                           quantity_before INTEGER NOT NULL,
                                           quantity_after INTEGER NOT NULL,
                                           reference_type VARCHAR(50),
                                           reference_id BIGINT,
                                           reason VARCHAR(500),
                                           performed_by BIGINT,
                                           created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                           CONSTRAINT fk_stock_transactions_item
                                               FOREIGN KEY (stock_item_id) REFERENCES garage.stock_items(id),
                                           CONSTRAINT chk_stock_transaction_quantity CHECK (quantity > 0),
                                           CONSTRAINT chk_stock_transaction_balances
                                               CHECK (quantity_before >= 0 AND quantity_after >= 0),
                                           CONSTRAINT chk_stock_transaction_type
                                               CHECK (transaction_type IN (
                                                                           'STOCK_IN', 'STOCK_OUT', 'DAMAGE', 'WASTAGE',
                                                                           'ADJUSTMENT_IN', 'ADJUSTMENT_OUT'
                                                   ))
);

CREATE INDEX idx_stock_transactions_item
    ON garage.stock_transactions(stock_item_id);
CREATE INDEX idx_stock_transactions_created_at
    ON garage.stock_transactions(created_at);

CREATE TABLE garage.grns (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             grn_number VARCHAR(50) NOT NULL UNIQUE,
                             supplier_id BIGINT NOT NULL,
                             status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                             received_at TIMESTAMP,
                             notes VARCHAR(500),
                             created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             CONSTRAINT fk_grns_supplier
                                 FOREIGN KEY (supplier_id) REFERENCES garage.suppliers(id),
                             CONSTRAINT chk_grns_status
                                 CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED'))
);

CREATE INDEX idx_grns_supplier_id ON garage.grns(supplier_id);
CREATE INDEX idx_grns_status ON garage.grns(status);

CREATE TABLE garage.grn_items (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  grn_id BIGINT NOT NULL,
                                  stock_item_id BIGINT NOT NULL,
                                  received_quantity INTEGER NOT NULL,
                                  unit_cost NUMERIC(12, 2) NOT NULL,
                                  CONSTRAINT fk_grn_items_grn
                                      FOREIGN KEY (grn_id) REFERENCES garage.grns(id),
                                  CONSTRAINT fk_grn_items_stock_item
                                      FOREIGN KEY (stock_item_id) REFERENCES garage.stock_items(id),
                                  CONSTRAINT chk_grn_items_quantity CHECK (received_quantity > 0),
                                  CONSTRAINT chk_grn_items_unit_cost CHECK (unit_cost >= 0),
                                  CONSTRAINT uq_grn_items_grn_stock_item UNIQUE (grn_id, stock_item_id)
);

CREATE INDEX idx_grn_items_grn_id ON garage.grn_items(grn_id);
CREATE INDEX idx_grn_items_stock_item_id ON garage.grn_items(stock_item_id);
