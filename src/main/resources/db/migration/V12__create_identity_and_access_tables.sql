-- Application identities are managed by Spring Boot, not Supabase Auth.
CREATE TABLE garage.user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id UUID NOT NULL,
    username VARCHAR(80) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_user_accounts_employee UNIQUE (employee_id),
    CONSTRAINT uq_user_accounts_username UNIQUE (username),
    CONSTRAINT fk_user_accounts_employee FOREIGN KEY (employee_id)
        REFERENCES garage.employees(id),
    CONSTRAINT ck_user_accounts_username CHECK (
        username = LOWER(BTRIM(username))
        AND username ~ '^[a-z0-9][a-z0-9._-]{2,79}$'
    ),
    CONSTRAINT ck_user_accounts_password_hash CHECK (LENGTH(BTRIM(password_hash)) > 0)
);

CREATE TABLE garage.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uq_roles_code UNIQUE (code),
    CONSTRAINT ck_roles_code CHECK (code ~ '^[A-Z][A-Z0-9_]{0,49}$')
);

CREATE TABLE garage.permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    description VARCHAR(255) NOT NULL,
    CONSTRAINT uq_permissions_code UNIQUE (code),
    CONSTRAINT ck_permissions_code CHECK (code ~ '^[a-z][a-z0-9_]*:[a-z][a-z0-9_]*$')
);

CREATE TABLE garage.user_account_roles (
    user_account_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_account_id, role_id),
    CONSTRAINT fk_user_account_roles_account FOREIGN KEY (user_account_id)
        REFERENCES garage.user_accounts(id) ON DELETE CASCADE,
    CONSTRAINT fk_user_account_roles_role FOREIGN KEY (role_id)
        REFERENCES garage.roles(id)
);
CREATE INDEX idx_user_account_roles_role ON garage.user_account_roles(role_id);

CREATE TABLE garage.role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id)
        REFERENCES garage.roles(id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id)
        REFERENCES garage.permissions(id)
);
CREATE INDEX idx_role_permissions_permission ON garage.role_permissions(permission_id);

-- These tables must only be accessed through the trusted backend DB connection.
-- No browser/Data API policies are created for application credentials.
ALTER TABLE garage.user_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE garage.roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE garage.permissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE garage.user_account_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE garage.role_permissions ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE garage.user_accounts, garage.roles, garage.permissions,
    garage.user_account_roles, garage.role_permissions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE garage.user_accounts_id_seq, garage.roles_id_seq,
    garage.permissions_id_seq FROM PUBLIC, anon, authenticated;
