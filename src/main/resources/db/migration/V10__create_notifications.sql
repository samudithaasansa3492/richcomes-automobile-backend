DROP TABLE IF EXISTS garage.notifications;
CREATE TABLE garage.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_id BIGINT,
    vehicle_id BIGINT,
    appointment_id BIGINT,

    type VARCHAR(50) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    recipient VARCHAR(150),
    message TEXT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    sent_at TIMESTAMP,
    failure_reason TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notifications_customer
        FOREIGN KEY (customer_id)
        REFERENCES garage.customers(id),

    CONSTRAINT fk_notifications_vehicle
        FOREIGN KEY (vehicle_id)
        REFERENCES garage.vehicles(id),

    CONSTRAINT fk_notifications_appointment
        FOREIGN KEY (appointment_id)
        REFERENCES garage.appointments(id)
);

CREATE INDEX idx_notifications_customer
    ON garage.notifications(customer_id);

CREATE INDEX idx_notifications_vehicle
    ON garage.notifications(vehicle_id);

CREATE INDEX idx_notifications_appointment
    ON garage.notifications(appointment_id);

CREATE INDEX idx_notifications_status
    ON garage.notifications(status);
